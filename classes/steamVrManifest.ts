/**
 * PetPlay's permanent SteamVR application registration: the `.vrmanifest` that
 * puts PetPlay in SteamVR's *Startup overlay apps* list, the launcher SteamVR
 * runs when it auto-launches it, and the SteamVR config files the registration
 * touches when SteamVR is not running.
 *
 * Everything here is pure (text in, text out) so it can be tested without
 * SteamVR; `utils/steamvr-app.ts` does the I/O.
 *
 * The manifest names its binary and image by paths *relative to itself*, which
 * SteamVR resolves against the manifest's directory. That keeps one layout for
 * every way PetPlay gets installed: a dev checkout generates the directory, and
 * a packaged build will ship the same files next to its executable.
 */

/**
 * The app key SteamVR files PetPlay under. A Steam store build switches to the
 * `steam.app.<id>` convention, which is why it lives in one place.
 */
export const STEAMVR_APP_KEY = "petplay.overlay";

export const STEAMVR_MANIFEST_FILE = "petplay.vrmanifest";
export const STEAMVR_LAUNCHER_FILE = "launch-petplay.sh";
export const STEAMVR_IMAGE_FILE = "petplay.png";

export type SteamVrManifestOptions = {
  appKey?: string;
  /** Launcher path, relative to the manifest's directory. */
  binaryPath: string;
  /** Image path, relative to the manifest's directory. */
  imagePath?: string;
  name?: string;
  description?: string;
  os?: typeof Deno.build.os;
  arch?: typeof Deno.build.arch;
};

/**
 * The field SteamVR reads the launcher from on this platform. Linux ARM64 (the
 * Steam Frame) has its own: a manifest with only `binary_path_linux` registers
 * there without being launchable.
 */
export function manifestBinaryPathField(
  os: typeof Deno.build.os = Deno.build.os,
  arch: typeof Deno.build.arch = Deno.build.arch,
): string {
  switch (os) {
    case "windows":
      return "binary_path_windows";
    case "darwin":
      return "binary_path_osx";
    default:
      return arch === "aarch64" ? "binary_path_linux_arm" : "binary_path_linux";
  }
}

/**
 * `is_dashboard_overlay` is what lists PetPlay under *Startup / Shutdown →
 * Choose startup overlay apps*, where SteamVR's own auto-launch toggle lives.
 */
export function buildSteamVrManifest(options: SteamVrManifestOptions): string {
  const application: Record<string, unknown> = {
    app_key: options.appKey ?? STEAMVR_APP_KEY,
    launch_type: "binary",
    [manifestBinaryPathField(options.os, options.arch)]: options.binaryPath,
    is_dashboard_overlay: true,
  };
  if (options.imagePath != null) application.image_path = options.imagePath;
  application.strings = {
    en_us: {
      name: options.name ?? "PetPlay",
      description: options.description ?? "Desktop, keyboard and spatial UI overlay for SteamVR",
    },
  };
  return JSON.stringify({ source: "builtin", applications: [application] }, null, 2) + "\n";
}

/** Single-quotes `arg` for bash, so paths with spaces or `$` survive verbatim. */
export function bashQuote(arg: string): string {
  return /^[A-Za-z0-9_@%+=:,./-]+$/.test(arg) ? arg : `'${arg.replaceAll("'", `'\\''`)}'`;
}

export type SteamVrLauncherOptions = {
  /** Directory the command runs in (the checkout, or the install directory). */
  workingDirectory: string;
  /** The command to run; for a checkout, `deno run … utils/steamvr-watch.ts --once`. */
  command: readonly string[];
};

/**
 * The script SteamVR runs. Two things it must do that a bare `deno run` can't:
 *
 * - **Leave the Steam runtime container.** SteamVR starts overlay apps inside
 *   its pressure-vessel runtime, where the host's Deno, native libraries,
 *   portals and capture helper are missing. `steam-runtime-launch-client
 *   --alongside-steam` runs the command next to Steam on the host instead
 *   (the same escape WayVR's launcher uses).
 * - **Keep a log.** Nothing else sees a SteamVR-launched process's output.
 */
export function buildSteamVrLauncher(options: SteamVrLauncherOptions): string {
  const cwd = bashQuote(options.workingDirectory);
  return [
    "#!/usr/bin/env bash",
    "# Generated by `deno task steamvr:register`. SteamVR runs this when it",
    "# auto-launches PetPlay; re-run the register task to change it.",
    "set -euo pipefail",
    "",
    'state_dir=${XDG_STATE_HOME:-"$HOME/.local/state"}/petplay',
    'mkdir -p "$state_dir"',
    'exec >>"$state_dir/steamvr-launch.log" 2>&1',
    `printf '%(%FT%T%z)T SteamVR launch requested (app key %s).\\n' -1 "\${STEAMVR_APPKEY:-unset}"`,
    "",
    `command=(${options.command.map(bashQuote).join(" ")})`,
    "if [[ -d /run/host/usr && -x /usr/bin/steam-runtime-launch-client ]]; then",
    "  printf 'Launching PetPlay outside the SteamVR runtime.\\n'",
    "  exec /usr/bin/steam-runtime-launch-client --alongside-steam \\",
    `    --directory=${cwd} --pass-env=STEAMVR_APPKEY -- "\${command[@]}"`,
    "fi",
    `cd ${cwd}`,
    'exec "${command[@]}"',
    "",
  ].join("\n");
}

// ---------------------------------------------------------------------------
// SteamVR config files, for registering while SteamVR is not running. While it
// runs, it owns these files and rewrites them on exit, so the OpenVR API is the
// only safe way to change them then.

type AppConfig = { manifest_paths?: string[] } & Record<string, unknown>;

/** SteamVR writes its config with three-space indentation; match it. */
function writeSteamVrJson(value: unknown): string {
  return JSON.stringify(value, null, 3) + "\n";
}

function parseAppConfig(text: string | null): AppConfig {
  if (text == null || text.trim() === "") return {};
  const parsed = JSON.parse(text);
  if (parsed == null || typeof parsed !== "object" || Array.isArray(parsed)) {
    throw new Error("appconfig.json is not a JSON object");
  }
  return parsed as AppConfig;
}

/** `appconfig.json` text listing `manifestPath`, keeping every other entry. */
export function appConfigWithManifest(text: string | null, manifestPath: string): string {
  const config = parseAppConfig(text);
  const paths = config.manifest_paths ?? [];
  if (paths.includes(manifestPath)) return writeSteamVrJson(config);
  return writeSteamVrJson({ ...config, manifest_paths: [...paths, manifestPath] });
}

/** `appconfig.json` text without `manifestPath`. */
export function appConfigWithoutManifest(text: string | null, manifestPath: string): string {
  const config = parseAppConfig(text);
  const paths = (config.manifest_paths ?? []).filter((path) => path !== manifestPath);
  return writeSteamVrJson({ ...config, manifest_paths: paths });
}

export function appConfigListsManifest(text: string | null, manifestPath: string): boolean {
  return (parseAppConfig(text).manifest_paths ?? []).includes(manifestPath);
}

/** `vrappconfig/<app key>.vrappconfig` text with `autolaunch` set, other fields kept. */
export function vrAppConfigWithAutoLaunch(text: string | null, autoLaunch: boolean): string {
  const config = text == null || text.trim() === "" ? {} : JSON.parse(text);
  return writeSteamVrJson({ last_launch_time: "0", ...config, autolaunch: autoLaunch });
}

export function vrAppConfigAutoLaunch(text: string | null): boolean {
  if (text == null || text.trim() === "") return false;
  return JSON.parse(text).autolaunch === true;
}
